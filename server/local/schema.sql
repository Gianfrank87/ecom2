CREATE TABLE IF NOT EXISTS ofertas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(255) NOT NULL,
  producto_ids TEXT NOT NULL DEFAULT '[]',
  descuento_o_precio_paquete NUMERIC(10,2) NOT NULL,
  tipo_descuento VARCHAR(50) NOT NULL DEFAULT 'precio_paquete' CHECK (tipo_descuento IN ('precio_paquete','porcentaje')),
  prioridad INTEGER NOT NULL DEFAULT 0,
  activa BOOLEAN NOT NULL DEFAULT TRUE,
  desactivada_por_stock BOOLEAN NOT NULL DEFAULT FALSE,
  producto_sin_stock_id BIGINT,
  producto_sin_stock_nombre VARCHAR(255)
);
CREATE TABLE IF NOT EXISTS pedido_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES pedidos(id),
  producto_id BIGINT NOT NULL REFERENCES productos(id),
  oferta_id BIGINT,
  cantidad INTEGER NOT NULL,
  precio_unitario NUMERIC(10,2) NOT NULL
);
CREATE TABLE IF NOT EXISTS mensajes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES pedidos(id),
  remitente VARCHAR(20) NOT NULL CHECK (remitente IN ('cliente','admin')),
  contenido TEXT NOT NULL,
  fecha TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  leido BOOLEAN NOT NULL DEFAULT FALSE,
  hilo_id INTEGER NOT NULL DEFAULT 1,
  tipo VARCHAR(20) NOT NULL DEFAULT 'mensaje' CHECK (tipo IN ('mensaje','sistema')),
  cerrado BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS configuraciones (
