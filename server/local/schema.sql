-- Isolated development database only. Never run against production.
CREATE TABLE IF NOT EXISTS categorias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS clientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  rol VARCHAR(20) NOT NULL DEFAULT 'cliente' CHECK (rol IN ('cliente', 'admin')),
  fecha_registro TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS productos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(255) NOT NULL,
  descripcion TEXT,
  precio NUMERIC(10,2) NOT NULL,
  stock INTEGER NOT NULL DEFAULT 0,
  categoria VARCHAR(100) NOT NULL REFERENCES categorias(nombre),
  imagen_url TEXT,
  imagenes TEXT,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  destacado BOOLEAN NOT NULL DEFAULT FALSE,
  orden INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS pedidos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id BIGINT NOT NULL REFERENCES clientes(id),
  fecha TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  total NUMERIC(10,2) NOT NULL,
  estado VARCHAR(50) NOT NULL DEFAULT 'pendiente'
    CHECK (estado IN ('pendiente','enviado','completado','esperando_aprobacion','pago_rechazado','pendiente_pago','aprobado')),
  metodo_pago VARCHAR(20) NOT NULL DEFAULT 'transferencia' CHECK (metodo_pago IN ('transferencia','efectivo','mercadopago')),
  recargo_aplicado NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (recargo_aplicado >= 0),
  entrega_nombre VARCHAR(120),
  entrega_email VARCHAR(255),
  entrega_telefono VARCHAR(40),
  entrega_direccion VARCHAR(240),
  entrega_notas TEXT,
  envio_destination_id INTEGER,
  envio_localidad VARCHAR(120),
  envio_provincia VARCHAR(120),
  envio_cp VARCHAR(20),
  envio_costo NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (envio_costo >= 0),
  mp_payment_id VARCHAR(80),
  mp_payment_status VARCHAR(40),
  mp_payment_status_detail VARCHAR(120),
  mp_merchant_order_id VARCHAR(120),
  mp_preference_id VARCHAR(120),
  mp_approved_at TIMESTAMPTZ,
  mp_last_webhook_at TIMESTAMPTZ,
  comprobante_url TEXT
);
